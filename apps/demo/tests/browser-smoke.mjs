import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const directory=path.resolve('test-results');fs.mkdirSync(directory,{recursive:true});
const external=process.env.DEMO_TEST_URL;
const url=external??'http://127.0.0.1:4174';
const server=external?null:spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4174'],{stdio:'ignore'});
let browser;
const checks=[];const errors=[];const network=[];
try{
  for(let i=0;i<50;i++){try{const response=await fetch(url);if(response.ok)break;}catch{}await new Promise(r=>setTimeout(r,200));}
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'light'});
  const p=await context.newPage();
  p.on('pageerror',e=>errors.push(e.message));
  p.on('request',r=>network.push(r.url()));
  await p.goto(url,{waitUntil:'networkidle'});
  await expect(p.getByRole('heading',{name:'Elegí cómo entrar'})).toBeVisible();
  await expect(p.locator('input[type=password]')).toHaveCount(0);
  await p.screenshot({animations:'disabled',path:path.join(directory,'access.png')});
  await p.getByRole('radio',{name:/Administrador/}).check();
  await p.getByRole('button',{name:'Confirmar y entrar'}).click();
  await expect(p.getByRole('heading',{name:'Resumen Académico'})).toBeVisible();
  await expect(p.getByText('Algoritmos y Estructuras de Datos',{exact:true}).first()).toBeVisible();
  await p.getByRole('button').filter({hasText:'Algoritmos y Estructuras de Datos'}).first().click();
  await expect(p.getByRole('dialog')).toBeVisible();
  await p.keyboard.press('Escape');
  await expect(p.getByRole('dialog')).not.toBeVisible();
  await p.screenshot({animations:'disabled',path:path.join(directory,'summary.png')});checks.push('password-free admin login and populated summary');
  const nav=async name=>{await p.locator('header').getByRole('link',{name,exact:true}).first().click();await expect(p.locator('main[data-pending-navigation]')).toHaveAttribute('data-pending-navigation','false',{timeout:20000});};
  await nav('Mapa');
  await expect(p.locator('[data-map-view-shell]')).toHaveAttribute('aria-hidden','false',{timeout:20000});
  await expect.poll(()=>p.locator('[data-node-id]').evaluateAll(nodes=>nodes.some(node=>{const r=node.getBoundingClientRect();return r.width>100&&r.right>0&&r.left<innerWidth&&r.bottom>100&&r.top<innerHeight;})),{timeout:10000}).toBe(true);
  await p.screenshot({animations:'disabled',path:path.join(directory,'map.png')});checks.push('interactive map loads through original navigation');
  await nav('Cursos');await expect(p.locator('[data-demo-page]')).toContainText('Algoritmos');checks.push('course catalog');
  await nav('Planificar');
  const termPrompt=p.getByRole('heading',{name:'Elegí dónde vas a trabajar'});
  if(await termPrompt.isVisible())await p.getByRole('button',{name:new RegExp(`${new Date().getFullYear()}-[12]`)}).first().click();
  await expect(p.getByRole('button',{name:'Confirmar plan'})).toBeVisible();
  await expect(p.locator('[data-planner-rail]')).toContainText('Algoritmos');checks.push('planner has seeded selections');
  await nav('Calendario');await expect(p.locator('[data-calendar-month]')).toBeVisible();
  await p.screenshot({animations:'disabled',path:path.join(directory,'calendar.png')});checks.push('calendar');
  await nav('Admin');await expect(p.getByRole('heading',{name:'Centro de control académico'})).toBeVisible();
  await p.getByPlaceholder('Nombre',{exact:true}).fill('Materia ficticia QA');
  await p.getByPlaceholder('Código',{exact:true}).first().fill('DEMO-QA');
  await p.locator('section').filter({hasText:'Agregar materia al catálogo'}).last().getByRole('button',{name:'Agregar materia',exact:true}).click();
  await expect(p.locator('input[value="Materia ficticia QA"]')).toBeVisible();
  await p.reload({waitUntil:'networkidle'});
  await expect(p.locator('input[value="Materia ficticia QA"]')).toBeVisible();checks.push('admin creates a course and data survives reload');
  await p.getByRole('button',{name:'Perfil',exact:true}).click();
  await p.getByRole('button',{name:'Visualizador',exact:true}).click();
  await expect(p.getByRole('heading',{name:'Resumen Académico'})).toBeVisible();
  await expect(p.locator('header').getByRole('link',{name:'Admin',exact:true})).toHaveCount(0);
  await nav('Planificar');await expect(p.getByRole('button',{name:'Confirmar plan'})).toBeDisabled();await expect(p.getByRole('button',{name:'Añadir materia'})).toBeDisabled();
  await p.goto(url+'/admin',{waitUntil:'networkidle'});await expect(p.getByRole('heading',{name:'Resumen Académico'})).toBeVisible();checks.push('viewer controls and direct admin URL are read-only');
  await p.setViewportSize({width:390,height:844});
  await p.screenshot({animations:'disabled',path:path.join(directory,'mobile-summary.png'),fullPage:true});
  expect(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);checks.push('mobile summary has no horizontal overflow');
  await p.getByRole('button',{name:'Perfil',exact:true}).click();await p.screenshot({animations:'disabled',path:path.join(directory,'mobile-profile.png'),fullPage:true});
  expect(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await p.getByRole('button',{name:'Restablecer demo'}).click();
  await p.getByRole('dialog').getByRole('button',{name:'Restablecer',exact:true}).click();
  await expect(p.getByRole('heading',{name:'Resumen Académico'})).toBeVisible();checks.push('reset returns synthetic state');
  const privateContext=await browser.newContext();const fresh=await privateContext.newPage();await fresh.goto(url);await expect(fresh.getByRole('heading',{name:'Elegí cómo entrar'})).toBeVisible();checks.push('independent visitors start with role selection');
  const origin=new URL(url).origin;
  expect(network.filter(x=>new URL(x).origin!==origin)).toEqual([]);
  expect(network.filter(x=>new URL(x).pathname.startsWith('/api/'))).toEqual([]);
  expect(errors).toEqual([]);checks.push('zero API network requests, zero external requests and no browser exceptions');
  fs.writeFileSync(path.join(directory,'browser-report.json'),JSON.stringify({status:'passed',checks,requests:network.length,externalRequests:0,apiNetworkRequests:0,errors},null,2));
  console.log(JSON.stringify({status:'passed',checks,requests:network.length,errors}));
}catch(e){fs.writeFileSync(path.join(directory,'browser-report.json'),JSON.stringify({status:'failed',checks,errors,failure:e.message},null,2));console.error(e);process.exitCode=1;}finally{await browser?.close();server?.kill();}
